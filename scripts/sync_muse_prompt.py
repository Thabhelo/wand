"""Sync the shared Muse onboarding prompt into web and native copy buttons."""
from pathlib import Path
import json, re, html
root = Path(__file__).resolve().parents[1]
prompt = (root / "web/muse-setup-prompt.txt").read_text().strip()
(root / "web/muse-setup.js").write_text("window.wandMuseSetupPrompt = " + json.dumps(prompt) + ";\n" + (root / "web/muse-copy.js").read_text())
(root / "agent/Sources/MacBridge/MuseSetupPrompt.swift").write_text('// Generated by scripts/sync_muse_prompt.py; edit web/muse-setup-prompt.txt.\nimport Foundation\nenum MuseSetupPrompt {\n    static let text = #"""\n' + prompt + '\n"""#\n}\n')

support = root / "site/public/support/index.html"
support.write_text(re.sub(r'(<textarea id="muse-setup-prompt"[^>]*>).*?(</textarea>)', lambda match: match[1] + html.escape(prompt) + match[2], support.read_text(), flags=re.S))
